import { terrariaObjectLayouts } from "./terraria-object-layouts.generated.js";

/**
 * Where a multi-tile object's styles sit on its sprite sheet (docs/assets.md, "Object frames"). Every style takes one
 * style cell of `styleWidth` × `styleHeight` pixels; within it, column `dx` of the object is at frame X `cellX[dx]` and
 * row `dy` at frame Y `cellY[dy]`. Styles advance along X (`horizontal`) or Y, `multiplier` cells per style (the extra
 * cells hold alternate placements, such as a chair facing right). After `wrap` cells (0: never) the next style starts
 * a new row (or column), `lineSkip` rows apart: the rows between hold the object's other states, such as a lamp
 * switched off.
 */
export interface ObjectLayout {
  readonly cellX: readonly number[];
  readonly cellY: readonly number[];
  readonly styleWidth: number;
  readonly styleHeight: number;
  readonly horizontal: boolean;
  readonly wrap: number;
  readonly multiplier: number;
  readonly lineSkip: number;
  /** How many styles items place; null when no item places the tile and the sheet's extent is unknown. */
  readonly styles: number | null;
  /** Styles placed as another shape inside their style cell (a table's top-only style): they resolve to nothing. */
  readonly irregular?: readonly number[];
}

/** The game-derived layouts by tile id, generated by scripts/object-layouts/export.mjs (ADR 0003). */
export interface ObjectLayoutTable {
  readonly gameVersion: string;
  readonly layouts: Readonly<Partial<Record<number, ObjectLayout>>>;
}

/** One tile of an object, `dx` columns right of and `dy` rows below the object's top-left tile. */
export interface ObjectPart { readonly dx: number; readonly dy: number }

/** What a tile's frame says about the object it belongs to; `originOffset` leads from the tile to the top-left tile. */
export interface ObjectFrame {
  readonly style: number;
  readonly part: ObjectPart;
  readonly originOffset: ObjectPart;
}

export interface ObjectTileFrame { readonly x: number; readonly y: number; readonly frameX: number; readonly frameY: number }

/** The frames of every part of `style` in a layout, row by row (alternate placement 0). */
export function layoutFrames(layout: ObjectLayout, style: number): (ObjectPart & { readonly frameX: number; readonly frameY: number })[] {
  const placed = style * layout.multiplier;
  const along = layout.wrap > 0 ? placed % layout.wrap : placed;
  const across = layout.wrap > 0 ? Math.floor(placed / layout.wrap) * layout.lineSkip : 0;
  const [column, row] = layout.horizontal ? [along, across] : [across, along];
  return layout.cellY.flatMap((y, dy) => layout.cellX.map((x, dx) => ({
    dx, dy, frameX: column * layout.styleWidth + x, frameY: row * layout.styleHeight + y,
  })));
}

/** The style and part a frame shows in a layout, or null for a frame that is not on its grid. */
export function layoutPart(layout: ObjectLayout, frameX: number, frameY: number): ObjectFrame | null {
  if (frameX < 0 || frameY < 0) return null;
  const column = Math.floor(frameX / layout.styleWidth);
  const row = Math.floor(frameY / layout.styleHeight);
  const dx = layout.cellX.indexOf(frameX - column * layout.styleWidth);
  const dy = layout.cellY.indexOf(frameY - row * layout.styleHeight);
  if (dx < 0 || dy < 0) return null;
  const [along, across] = layout.horizontal ? [column, row] : [row, column];
  let placed = along;
  if (layout.wrap > 0) {
    if (along >= layout.wrap) return null;
    placed += Math.floor(across / layout.lineSkip) * layout.wrap;
  } else if (across >= layout.lineSkip) return null;
  const style = Math.floor(placed / layout.multiplier);
  if ((layout.styles !== null && style >= layout.styles) || layout.irregular?.includes(style) === true) return null;
  return { style, part: { dx, dy }, originOffset: { dx: -dx, dy: -dy } };
}

/** The layout of a vanilla tile id; undefined for tiles that are not observed multi-tile objects (and mod tiles). */
export function objectLayout(tileId: number): ObjectLayout | undefined {
  return terrariaObjectLayouts.layouts[tileId];
}

/** The style and part of an object a tile's frame shows; null for unknown ids and frames outside the sheet. */
export function resolveObject(tileId: number, frameX: number, frameY: number): ObjectFrame | null {
  const layout = objectLayout(tileId);
  return layout === undefined ? null : layoutPart(layout, frameX, frameY);
}

/**
 * The frames of every tile of an object of `style` whose top-left tile is `topLeft`, row by row: what placing the
 * object or changing its style writes. Null for unknown ids and styles outside the sheet.
 */
export function objectFrames(tileId: number, style: number, topLeft: { readonly x: number; readonly y: number }): ObjectTileFrame[] | null {
  const layout = objectLayout(tileId);
  if (layout === undefined || !Number.isInteger(style) || style < 0 || (layout.styles !== null && style >= layout.styles) || layout.irregular?.includes(style) === true) return null;
  return layoutFrames(layout, style).map(({ dx, dy, frameX, frameY }) => ({ x: topLeft.x + dx, y: topLeft.y + dy, frameX, frameY }));
}
