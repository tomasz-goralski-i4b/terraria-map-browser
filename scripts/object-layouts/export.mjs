// Turns the object layout observation (observe.ps1, ADR 0003) into the table the model reads:
//   node scripts/object-layouts/export.mjs local-renders/object-layouts.json
// Per frame-important tile type: object size, where its parts sit in a style cell, and how styles advance and wrap on
// the sheet. A type is written only when its layout reproduces the frames the game wrote for every style it placed;
// the others are listed with the reason. Only numbers are written, no texture and no code. The output,
// packages/world-model/src/terraria-object-layouts.generated.ts, is regenerated, never edited by hand.
// Build first: the frames are checked with the model's own layoutFrames (packages/world-model/dist).
import { readFileSync, writeFileSync } from "node:fs";
import { layoutFrames, layoutPart } from "../../packages/world-model/dist/object-frames.js";

export const OUTPUT = "packages/world-model/src/terraria-object-layouts.generated.ts";

function fail(message) {
  throw new Error(`object layout export: ${message}`);
}

/** The layout of one observed type, or the reason it has none. */
export function layoutOf(observed) {
  const { layout, styles } = observed;
  if (layout === null) return { reason: "no placement data" };
  const base = styles[0]?.tiles;
  if (base === null || base === undefined) return { reason: "style 0 not placed" };
  if (base.length !== layout.width * layout.height) return { reason: "placement is not the whole object" };
  // An object's first style starts the sheet; a lone tile framed anywhere else is framed by its neighbours (platforms).
  if (!base.some(([dx, dy, frameX, frameY]) => dx === 0 && dy === 0 && frameX === 0 && frameY === 0)) return { reason: "style 0 is not at the sheet's origin" };
  const frameAt = (dx, dy) => base.find(([x, y]) => x === dx && y === dy);
  const cellX = [], cellY = [];
  for (let dx = 0; dx < layout.width; dx++) cellX.push(frameAt(dx, 0)?.[2] ?? fail(`type ${String(observed.type)} has no part (${String(dx)}, 0)`));
  for (let dy = 0; dy < layout.height; dy++) cellY.push(frameAt(0, dy)?.[3] ?? fail(`type ${String(observed.type)} has no part (0, ${String(dy)})`));
  const result = {
    cellX, cellY, styleWidth: layout.fullWidth, styleHeight: layout.fullHeight, horizontal: layout.horizontal,
    wrap: layout.wrap, multiplier: layout.multiplier, lineSkip: layout.lineSkip,
    styles: observed.itemStyles > 0 ? observed.itemStyles : null,
  };
  const irregular = [];
  for (const { style, tiles } of styles) {
    if (tiles === null) return { reason: `style ${String(style)} not placed` };
    const expected = layoutFrames(result, style);
    const regular = tiles.length === expected.length && tiles.every(([dx, dy, frameX, frameY]) => {
      const frame = expected.find((part) => part.dx === dx && part.dy === dy);
      return frame?.frameX === frameX && frame.frameY === frameY;
    });
    if (regular) continue;
    // Another shape that stays inside its own style cell can be told apart and resolved to nothing; any other frame
    // would resolve to a wrong style.
    if (style === 0 || !tiles.every(([, , frameX, frameY]) => layoutPart(result, frameX, frameY)?.style === style)) {
      return { reason: `style ${String(style)} is framed by more than its style` };
    }
    irregular.push(style);
  }
  return { layout: irregular.length === 0 ? result : { ...result, irregular } };
}

export function exportLayouts(observed) {
  if (observed.complete !== true) fail("the observation is incomplete");
  if (!Array.isArray(observed.types)) fail("the observation has no types");
  const layouts = {};
  const skipped = [];
  for (const type of observed.types) {
    const { layout, reason } = layoutOf(type);
    if (layout === undefined) skipped.push([type.type, reason]);
    else layouts[type.type] = layout;
  }
  return { gameVersion: observed.gameVersion, layouts, skipped };
}

/** The generated module: one line per layout, and the skipped types as a comment. */
export function moduleText({ gameVersion, layouts, skipped }) {
  const lines = Object.entries(layouts).map(([type, layout]) => `    ${type}: ${JSON.stringify(layout).replace(/"(\w+)":/g, "$1: ")},`);
  const reasons = new Map();
  for (const [type, reason] of skipped) reasons.set(reason, [...(reasons.get(reason) ?? []), type]);
  const comment = [...reasons].map(([reason, types]) => `// ${reason}: ${types.join(", ")}`);
  return `// Generated by scripts/object-layouts/export.mjs from the object layout observer (ADR 0003). Do not edit by hand:
// regenerate it after a game update (scripts/object-layouts/README.md).
// Frame-important types without a layout, by reason:
${comment.join("\n")}
import type { ObjectLayoutTable } from "./object-frames.js";

export const terrariaObjectLayouts: ObjectLayoutTable = {
  gameVersion: ${JSON.stringify(gameVersion)},
  layouts: {
${lines.join("\n")}
  },
};
`;
}

if (process.argv[1]?.endsWith("export.mjs")) {
  const input = process.argv[2] ?? fail("usage: node scripts/object-layouts/export.mjs <observation.json>");
  const data = exportLayouts(JSON.parse(readFileSync(input, "utf8")));
  writeFileSync(OUTPUT, moduleText(data));
  console.log(`wrote ${OUTPUT}: ${String(Object.keys(data.layouts).length)} layouts, ${String(data.skipped.length)} types skipped`);
}
