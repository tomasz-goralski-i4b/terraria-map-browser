// Turns the sprite paint observation (observe.ps1, ADR 0003) into the table the renderer reads:
//   node scripts/sprite-paint/export.mjs local-renders/paint.json
// The special groups the game paints trees and grass with (docs/assets.md, "Paint and inactive tiles"): per group its
// hue and saturation range, hue offset and inversion, and which tile types (by style) and tree foliage use which group.
// Only numbers are written, no texture and no code. The output,
// packages/renderer/src/palette/terraria-paint-groups.generated.ts, is regenerated, never edited by hand.
import { readFileSync, writeFileSync } from "node:fs";

export const OUTPUT = "packages/renderer/src/palette/terraria-paint-groups.generated.ts";
/** The styles observed per tile type and foliage index, in order. */
export const STYLES = [-1, 0, 1, 2, 3, 4, 5, 6, 7, 8];

function fail(message) {
  throw new Error(`sprite paint export: ${message}`);
}

/**
 * The groups that use special groups, as [minHue, maxHue, minSaturation, maxSaturation, hueOffset, invert (0/1)], and
 * per tile type and foliage index the group (1-based; 0 for none) of each of STYLES. Entries without any group are left
 * out; an entry whose groups do not depend on the style keeps one.
 */
export function paintGroups(observed) {
  if (!Array.isArray(observed.groups)) fail("the observation has no special groups");
  const groups = [];
  const byKey = { tile: new Map(), foliage: new Map() };
  for (const { settings, keys } of observed.groups) {
    let group = 0;
    if (settings.UseSpecialGroups === true) {
      groups.push([
        settings.SpecialGroupMinimalHueValue, settings.SpecialGroupMaximumHueValue,
        settings.SpecialGroupMinimumSaturationValue, settings.SpecialGroupMaximumSaturationValue,
        settings.HueTestOffset, settings.InvertSpecialGroupResult === true ? 1 : 0,
      ]);
      group = groups.length;
    }
    for (const key of keys) {
      const [kind, id, style] = key.split(":");
      const table = byKey[kind] ?? fail(`unknown key ${String(key)}`);
      const at = STYLES.indexOf(Number(style));
      if (at < 0) fail(`unexpected style in ${String(key)}`);
      const styles = table.get(Number(id)) ?? table.set(Number(id), STYLES.map(() => -1)).get(Number(id));
      styles[at] = group;
    }
  }
  const rows = (table) => [...table].sort(([a], [b]) => a - b).flatMap(([id, styles]) => {
    if (styles.includes(-1)) fail(`id ${String(id)} misses a style`);
    if (styles.every((group) => group === 0)) return [];
    return [[id, ...(styles.every((group) => group === styles[0]) ? [styles[0]] : styles)]];
  });
  return { gameVersion: observed.gameVersion, groups, tiles: rows(byKey.tile), foliage: rows(byKey.foliage) };
}

if (process.argv[1]?.endsWith("export.mjs")) {
  const input = process.argv[2] ?? fail("usage: node scripts/sprite-paint/export.mjs <observation.json>");
  const data = paintGroups(JSON.parse(readFileSync(input, "utf8")));
  const text = `// Generated by scripts/sprite-paint/export.mjs from the sprite paint observer (ADR 0003). Do not edit by hand:
// regenerate it after a game update (scripts/sprite-paint/observe.ps1).
import type { PaintGroupData } from "./sprite-paint.js";

export const terrariaPaintGroups: PaintGroupData = ${JSON.stringify(data)};
`;
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}: ${String(data.groups.length)} groups, ${String(data.tiles.length)} tile types, ${String(data.foliage.length)} foliage sheets`);
}
